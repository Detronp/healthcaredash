export function ageFrom(dob, ref = new Date("2026-11-22")) {
  const d = new Date(dob);
  let a = ref.getFullYear() - d.getFullYear();
  const m = ref.getMonth() - d.getMonth();
  if (m < 0 || (m === 0 && ref.getDate() < d.getDate())) a--;
  return a;
}
